import fs from 'node:fs'
import path from 'node:path'

import ts from 'typescript'

/** Resolve generated directory namespaces through their explicit ESM barrel. */
export function normalizeGeneratedImports(directory) {
  let changed = 0
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      changed += normalizeGeneratedImports(file)
      continue
    }
    if (!entry.isFile() || !entry.name.endsWith('.ts')) continue
    const original = fs.readFileSync(file, 'utf8')
    let normalized = removeGeneratedTslintHeader(original)
    const source = ts.createSourceFile(file, normalized, ts.ScriptTarget.Latest, true)
    const replacements = []
    for (const statement of source.statements) {
      const replacement = namespaceReplacement(statement, source, file)
      if (replacement !== undefined) replacements.push(replacement)
    }
    for (const replacement of replacements.toReversed()) {
      normalized = normalized.slice(0, replacement.start) + replacement.value + normalized.slice(replacement.end)
    }
    if (normalized !== original) {
      fs.writeFileSync(file, normalized)
      changed++
    }
  }
  return changed
}

function namespaceReplacement(statement, source, file) {
  if (!ts.isImportDeclaration(statement) || !statement.importClause?.isTypeOnly
    || statement.importClause.namedBindings === undefined
    || !ts.isNamespaceImport(statement.importClause.namedBindings)
    || !ts.isStringLiteral(statement.moduleSpecifier)) return
  const specifier = statement.moduleSpecifier.text
  if (!specifier.startsWith('./') && !specifier.startsWith('../')) return
  const directory = path.resolve(path.dirname(file), specifier)
  const isDirectory = fs.existsSync(directory) && fs.statSync(directory).isDirectory()
  // Solidity-derived namespace directories such as Internal.sol contain dots.
  if (!isDirectory && path.extname(specifier) !== '') return
  const target = path.join(directory, 'index.ts')
  if (!fs.existsSync(target) || !fs.statSync(target).isFile()) {
    throw new Error(`Generated namespace ${specifier} in ${file} has no index.ts`)
  }
  return {
    start: statement.moduleSpecifier.getStart(source) + 1,
    end: statement.moduleSpecifier.getEnd() - 1,
    value: `${specifier.replace(/\/+$/, '')}/index.js`,
  }
}

/** Remove only the exact obsolete pragma emitted after TypeChain's generation marker. */
function removeGeneratedTslintHeader(source) {
  const marker = '/* Autogenerated file. Do not edit manually. */\n'
  const pragma = '/* tslint:disable */\n'
  return source.startsWith(marker + pragma) ? marker + source.slice(marker.length + pragma.length) : source
}
